CREATE EXTENSION IF NOT EXISTS postgis;

-- Remove the obsolete demo table from existing development databases.
DROP TABLE IF EXISTS greetings;

CREATE TABLE IF NOT EXISTS users (
    id integer GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    username varchar(255) NOT NULL UNIQUE,
    hashed_password char(60) NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS sessions (
    token text PRIMARY KEY,
    data bytea NOT NULL,
    expiry timestamptz NOT NULL
);

CREATE INDEX IF NOT EXISTS sessions_expiry_idx ON sessions (expiry);

-- Based on the production schema exported on 2026-10-13 (PostgreSQL 16.9).
-- Keep table names, columns and types compatible with data-only imports.
-- Use native deletion rules and immediate foreign-key checks.
CREATE TABLE IF NOT EXISTS photos_location (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    city text NOT NULL,
    country text NOT NULL,
    tzoffset integer NOT NULL,
    CONSTRAINT unique_city_country UNIQUE (city, country)
);

