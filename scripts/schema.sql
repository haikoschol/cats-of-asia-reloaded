CREATE TABLE IF NOT EXISTS photos_coordinates (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    altitude double precision NOT NULL,
    location_id bigint NOT NULL REFERENCES photos_location (id) ON DELETE CASCADE,
    point geography(Point, 4326) NOT NULL,
    CONSTRAINT unique_point_altitude UNIQUE (point, altitude)
);

CREATE TABLE IF NOT EXISTS photos_photo (
    id uuid PRIMARY KEY,
    filename varchar(255) NOT NULL,
    sha256 varchar(64) NOT NULL UNIQUE,
    timestamp timestamptz NOT NULL,
    coordinates_id bigint REFERENCES photos_coordinates (id) ON DELETE SET NULL
);

CREATE TABLE IF NOT EXISTS photos_rawmetadata (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    metadata jsonb NOT NULL,
    photo_id varchar(64) NOT NULL REFERENCES photos_photo (sha256) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS photos_platform (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL UNIQUE,
    profile_url varchar(200) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS photos_post (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamptz NOT NULL,
    photo_id varchar(64) NOT NULL REFERENCES photos_photo (sha256) ON DELETE CASCADE,
    platform_id bigint NOT NULL REFERENCES photos_platform (id) ON DELETE CASCADE,
    CONSTRAINT unique_photo_platform UNIQUE (photo_id, platform_id)
);

CREATE INDEX IF NOT EXISTS photos_coordinates_point_idx
    ON photos_coordinates USING gist (point);
CREATE INDEX IF NOT EXISTS photos_coordinates_location_id_idx
    ON photos_coordinates (location_id);
CREATE INDEX IF NOT EXISTS photos_photo_coordinates_id_idx
    ON photos_photo (coordinates_id);
CREATE INDEX IF NOT EXISTS photos_rawmetadata_photo_id_idx
    ON photos_rawmetadata (photo_id);
CREATE INDEX IF NOT EXISTS photos_post_photo_id_idx
    ON photos_post (photo_id);
CREATE INDEX IF NOT EXISTS photos_post_platform_id_idx
    ON photos_post (platform_id);
