CREATE EXTENSION IF NOT EXISTS postgis;

CREATE TABLE IF NOT EXISTS greetings (
    id integer GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    greeting varchar(255) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS users (
    id integer GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    username varchar(255) NOT NULL UNIQUE,
    hashed_password char(60) NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS sessions (
    token text PRIMARY KEY,
    data bytea NOT NULL,
    expiry timestamptz NOT NULL
);

CREATE INDEX IF NOT EXISTS sessions_expiry_idx ON sessions (expiry);

-- Application schema exported from production with pg_dump --schema-only
-- --no-owner --no-privileges --table='public.photos_*' on 2026-10-13.
-- Production uses PostgreSQL 16.9; Django's internal tables are not copied.
CREATE TABLE IF NOT EXISTS photos_location (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    city text NOT NULL,
    country text NOT NULL,
    tzoffset integer NOT NULL,
    CONSTRAINT unique_city_country UNIQUE (city, country)
);

CREATE TABLE IF NOT EXISTS photos_coordinates (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    altitude double precision NOT NULL,
    location_id bigint NOT NULL,
    point geography(Point, 4326) NOT NULL,
    CONSTRAINT photos_coordinates_location_id_c511f4b7_fk_photos_location_id
        FOREIGN KEY (location_id) REFERENCES photos_location (id) DEFERRABLE INITIALLY DEFERRED,
    CONSTRAINT unique_point_altitude UNIQUE (point, altitude)
);

CREATE TABLE IF NOT EXISTS photos_photo (
    id uuid PRIMARY KEY,
    filename varchar(255) NOT NULL,
    sha256 varchar(64) NOT NULL UNIQUE,
    timestamp timestamptz NOT NULL,
    coordinates_id bigint,
    CONSTRAINT photos_photo_coordinates_id_244b17b6_fk_photos_coordinates_id
        FOREIGN KEY (coordinates_id) REFERENCES photos_coordinates (id) DEFERRABLE INITIALLY DEFERRED
);

CREATE TABLE IF NOT EXISTS photos_rawmetadata (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    metadata jsonb NOT NULL,
    photo_id varchar(64) NOT NULL,
    CONSTRAINT photos_rawmetadata_photo_id_31b5def8_fk_photos_photo_sha256
        FOREIGN KEY (photo_id) REFERENCES photos_photo (sha256) DEFERRABLE INITIALLY DEFERRED
);

CREATE TABLE IF NOT EXISTS photos_platform (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL UNIQUE,
    profile_url varchar(200) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS photos_post (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamptz NOT NULL,
    photo_id varchar(64) NOT NULL,
    platform_id bigint NOT NULL,
    CONSTRAINT photos_post_photo_id_cd9e8f12_fk_photos_photo_sha256
        FOREIGN KEY (photo_id) REFERENCES photos_photo (sha256) DEFERRABLE INITIALLY DEFERRED,
    CONSTRAINT photos_post_platform_id_8f06aba8_fk_photos_platform_id
        FOREIGN KEY (platform_id) REFERENCES photos_platform (id) DEFERRABLE INITIALLY DEFERRED,
    CONSTRAINT unique_photo_platform UNIQUE (photo_id, platform_id)
);

-- Update local databases created by the earlier, code-derived version of this
-- schema. Only the known old foreign keys and index names are changed; rows stay.
DO $$
DECLARE
    item record;
BEGIN
    FOR item IN SELECT * FROM (VALUES
        ('photos_coordinates', 'photos_coordinates_location_id_fkey', 'photos_coordinates_location_id_c511f4b7_fk_photos_location_id', 'FOREIGN KEY (location_id) REFERENCES photos_location (id)'),
        ('photos_photo', 'photos_photo_coordinates_id_fkey', 'photos_photo_coordinates_id_244b17b6_fk_photos_coordinates_id', 'FOREIGN KEY (coordinates_id) REFERENCES photos_coordinates (id)'),
        ('photos_rawmetadata', 'photos_rawmetadata_photo_id_fkey', 'photos_rawmetadata_photo_id_31b5def8_fk_photos_photo_sha256', 'FOREIGN KEY (photo_id) REFERENCES photos_photo (sha256)'),
        ('photos_post', 'photos_post_photo_id_fkey', 'photos_post_photo_id_cd9e8f12_fk_photos_photo_sha256', 'FOREIGN KEY (photo_id) REFERENCES photos_photo (sha256)'),
        ('photos_post', 'photos_post_platform_id_fkey', 'photos_post_platform_id_8f06aba8_fk_photos_platform_id', 'FOREIGN KEY (platform_id) REFERENCES photos_platform (id)')
    ) AS keys(table_name, old_name, new_name, definition)
    LOOP
        IF EXISTS (SELECT 1 FROM pg_constraint
                   WHERE conrelid = to_regclass('public.' || item.table_name)
                     AND conname = item.old_name) THEN
            EXECUTE format('ALTER TABLE %I DROP CONSTRAINT %I', item.table_name, item.old_name);
            IF NOT EXISTS (SELECT 1 FROM pg_constraint
                           WHERE conrelid = to_regclass('public.' || item.table_name)
                             AND conname = item.new_name) THEN
                EXECUTE format('ALTER TABLE %I ADD CONSTRAINT %I %s DEFERRABLE INITIALLY DEFERRED',
                               item.table_name, item.new_name, item.definition);
            END IF;
        END IF;
    END LOOP;

    FOR item IN SELECT * FROM (VALUES
        ('photos_coordinates_point_idx', 'photos_coordinates_point_a1ffe3a6_id'),
        ('photos_coordinates_location_id_idx', 'photos_coordinates_location_id_c511f4b7'),
        ('photos_photo_coordinates_id_idx', 'photos_photo_coordinates_id_244b17b6'),
        ('photos_rawmetadata_photo_id_idx', 'photos_rawmetadata_photo_id_31b5def8'),
        ('photos_post_photo_id_idx', 'photos_post_photo_id_cd9e8f12'),
        ('photos_post_platform_id_idx', 'photos_post_platform_id_8f06aba8')
    ) AS indexes(old_name, new_name)
    LOOP
        IF to_regclass('public.' || item.old_name) IS NOT NULL THEN
            IF to_regclass('public.' || item.new_name) IS NULL THEN
                EXECUTE format('ALTER INDEX %I RENAME TO %I', item.old_name, item.new_name);
            ELSE
                EXECUTE format('DROP INDEX %I', item.old_name);
            END IF;
        END IF;
    END LOOP;
END $$;

